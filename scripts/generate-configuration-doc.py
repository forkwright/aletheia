#!/usr/bin/env python3
"""Generate and verify the field reference in docs/CONFIGURATION.md from the
`AletheiaConfig` schema in `crates/taxis/src/config/`.

`AletheiaConfig` (crates/taxis/src/config/mod.rs) is the SSOT for the TOML
config surface: every section, field, type, default, and `#[serde(...)]`
rename/alias lives there as compiled, type-checked source. This generator
walks that struct tree (following nested config structs, `Vec<Struct>`,
`HashMap<String, Struct>`, and cross-crate config types such as
`eidos::training::TrainingConfig`) and renders a field-reference table for
every section into the generated block of docs/CONFIGURATION.md, replacing
the prior hand-maintained tables that had drifted ~11 ways from the schema
(aletheia#5774).

Defaults are read from each struct's `impl Default` block (or, absent one,
derived from `#[derive(Default)]` primitive semantics and each enum's
`#[default]` variant). A default expression that is a local same-file
constant, or a single-hop cross-crate `path::CONST` / `path::Type::default()`
field access, is resolved to its literal value; anything not resolvable in a
bounded number of hops is rendered as the literal Rust expression rather than
guessed, so the doc never states a fabricated number.

Usage:
    python3 scripts/generate-configuration-doc.py
    python3 scripts/generate-configuration-doc.py --check

--check exits 0 when the committed doc's generated block matches freshly
generated output and non-zero with a clear instruction to regenerate.
"""

